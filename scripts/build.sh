#!/usr/bin/env bash
# Builds the single-file plugin in dist/: stamps the version from VERSION and embeds the settings
# window files, so the plugin can be installed from one URL (for example swiftbar://addplugin).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/src/dev-servers.sh"
OUT="$ROOT/dist/dev-servers.sh"
VERSION="$(tr -d '[:space:]' < "$ROOT/VERSION")"

for f in "$ROOT/src/settings/server.py" "$ROOT/src/settings/index.html"; do
  if grep -q '^__DEV_SERVERS_EOF__$' "$f"; then
    echo "error: $f contains the heredoc terminator" >&2
    exit 1
  fi
done

mkdir -p "$ROOT/dist"
{
  awk '/^# >>> settings-assets$/ { exit } { print }' "$SRC"
  echo "# >>> settings-assets"
  echo "# Writes the settings window's files into \$1. Generated by scripts/build.sh from src/settings."
  echo "write_assets() {"
  echo "  cat > \"\$1/server.py\" <<'__DEV_SERVERS_EOF__'"
  cat "$ROOT/src/settings/server.py"
  echo "__DEV_SERVERS_EOF__"
  echo "  cat > \"\$1/index.html\" <<'__DEV_SERVERS_EOF__'"
  cat "$ROOT/src/settings/index.html"
  echo "__DEV_SERVERS_EOF__"
  echo "}"
  awk 'found { print } /^# <<< settings-assets$/ { found = 1; print }' "$SRC"
} | sed -e "s/^readonly VERSION=\"dev\"$/readonly VERSION=\"$VERSION\"/" \
  -e "s|^# <xbar.version>dev</xbar.version>$|# <xbar.version>v$VERSION</xbar.version>|" > "$OUT"

chmod +x "$OUT"
echo "Built $OUT (v$VERSION)"
